/** Which face the app is drawn in; the system decides only when it is asked to. */
enum class ThemeMode(val id: String) {
    SYSTEM("system"),
    LIGHT("light"),
    DARK("dark"),
    ;

    companion object {
        /** The stored id, or the mode that asks the system when nothing has been said. */
        fun from(id: String?): ThemeMode = entries.firstOrNull { it.id == id } ?: SYSTEM
    }
}

/** One of the prepared colour schemes, or the colours the user mixes themselves. */
enum class ThemePreset(val id: String) {
    DEFAULT("default"),
    GITHUB("github"),
    TOKYO_NIGHT("tokyo_night"),
    DRACULA("dracula"),
    NORD("nord"),
    ONE_DARK("one_dark"),
    SOLARIZED("solarized"),
    GRUVBOX("gruvbox"),
    CATPPUCCIN("catppuccin"),
    CHINA_RED("china_red"),
    PERSIMMON("persimmon"),
    LEMON("lemon"),
    FOREST("forest"),
    MINT("mint"),
    SKY_BLUE("sky_blue"),
    GRAPE("grape"),
    CUSTOM("custom"),
    ;

    companion object {
        /** The stored id, or the plain default when it names no preset this app knows. */
        fun from(id: String?): ThemePreset = entries.firstOrNull { it.id == id } ?: DEFAULT
    }
}

/** Whether a mode draws dark, with the system answering only when it is asked to. */
@Composable
fun ThemeMode.isDark(): Boolean = when (this) {
    ThemeMode.SYSTEM -> isSystemInDarkTheme()
    ThemeMode.LIGHT -> false
    ThemeMode.DARK -> true
}

